export default function Sidebar({ isOpen, activePage, onNavigate }) {
  const renderSection = (items, title) => (
    <div className="sidebar-section">
      {title && isOpen && <div className="sidebar-section-title">{title}</div>}
      {items.map((item) => {
        const Icon = item.icon
        return (
          <button
            key={item.id}
            id={`sidebar-${item.id}`}
            className={`sidebar-item ${activePage === item.id ? 'active' : ''}`}
            onClick={() => onNavigate(item.id)}
            title={item.label}
            aria-label={item.label}
            aria-current={activePage === item.id ? 'page' : undefined}
          >
            <Icon filled={activePage === item.id} />
            <span className="sidebar-label">{item.label}</span>
          </button>
        )
      })}
    </div>
  )

  return (
    <aside
      id="main-sidebar"
      className={`sidebar ${isOpen ? 'open' : 'collapsed'}`}
      role="navigation"
      aria-label="Main navigation"
    >
      {renderSection(SIDEBAR_NAV, null)}
      {renderSection(SIDEBAR_LIB, 'Library')}
      {renderSection(SIDEBAR_MORE, 'More')}
    </aside>
  )
}
